/**
 * The SportnNote wordmark as vector shapes (founder 2026-11-08, option 2d;
 * docs/security/breaks/brand-cream.md). Reads the brand font once and writes:
 *   src/brand/wordmark.ts               — the shapes, for <Wordmark> (app, launch screen)
 *   assets/brand/sportnnote-wordmark.svg — the same, coloured, for the website and print
 * so the name is drawn identically everywhere, with no font loading.
 *
 *   npm i --no-save opentype.js@1.3.4 && node scripts/build-wordmark.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const opentype = require('opentype.js');

const FONT_NAME = 'BarlowCondensed_800ExtraBold_Italic';
const FONT = join(ROOT, 'node_modules/@expo-google-fonts/barlow-condensed/800ExtraBold_Italic', `${FONT_NAME}.ttf`);
const SIZE = 100;
/** the outline, as in option 2d (font size ÷ 14) */
const STROKE = SIZE / 14;
export const COLORS = { sport: '#C6EE3E', n: '#14181D', note: '#FFFFFF', key: '#0A3A2B' };

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const text = 'SportnNote';
const partOf = (i) => (i < 5 ? 'sport' : i === 5 ? 'n' : 'note');
const glyphs = font.stringToGlyphs(text);
const scale = SIZE / font.unitsPerEm;
const paths = { sport: new opentype.Path(), n: new opentype.Path(), note: new opentype.Path() };
let x = 0;
glyphs.forEach((g, i) => {
  paths[partOf(i)].extend(g.getPath(x, 0, SIZE));
  x += g.advanceWidth * scale + (glyphs[i + 1] ? font.getKerningValue(g, glyphs[i + 1]) * scale : 0);
});
// the box around all three, with room for the outline
const box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };
for (const p of Object.values(paths)) {
  const b = p.getBoundingBox();
  box.x1 = Math.min(box.x1, b.x1); box.y1 = Math.min(box.y1, b.y1); box.x2 = Math.max(box.x2, b.x2); box.y2 = Math.max(box.y2, b.y2);
}
const pad = STROKE / 2 + 1;
const dx = -box.x1 + pad, dy = -box.y1 + pad;
const shifted = {};
for (const [k, p] of Object.entries(paths)) {
  for (const c of p.commands) for (const key of ['x', 'x1', 'x2']) if (key in c) c[key] += dx;
  for (const c of p.commands) for (const key of ['y', 'y1', 'y2']) if (key in c) c[key] += dy;
  shifted[k] = p.toPathData(2);
}
const width = +(box.x2 - box.x1 + 2 * pad).toFixed(2), height = +(box.y2 - box.y1 + 2 * pad).toFixed(2);

const ts = `/** GENERATED by scripts/build-wordmark.mjs from ${FONT_NAME}.ttf — do not edit.
 *  The SportnNote wordmark as vector shapes (brand-cream.md): "Sport", "n" and
 *  "Note" in one coordinate box, with room for the outline. */
export const WORDMARK = {
  font: '${FONT_NAME}',
  stroke: ${STROKE.toFixed(3)},
  width: ${width},
  height: ${height},
  parts: {
    sport: '${shifted.sport}',
    n: '${shifted.n}',
    note: '${shifted.note}',
  },
} as const;
`;
mkdirSync(join(ROOT, 'src/brand'), { recursive: true });
writeFileSync(join(ROOT, 'src/brand/wordmark.ts'), ts);

const o = `stroke="${COLORS.key}" stroke-width="${STROKE.toFixed(3)}" stroke-linejoin="round"`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="SportnNote">
<path d="${shifted.sport}" fill="${COLORS.key}" ${o}/><path d="${shifted.note}" fill="${COLORS.key}" ${o}/>
<path d="${shifted.sport}" fill="${COLORS.sport}"/><path d="${shifted.n}" fill="${COLORS.n}"/><path d="${shifted.note}" fill="${COLORS.note}"/>
</svg>
`;
writeFileSync(join(ROOT, 'assets/brand/sportnnote-wordmark.svg'), svg);
console.log('wrote src/brand/wordmark.ts and assets/brand/sportnnote-wordmark.svg', { width, height });
