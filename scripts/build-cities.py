#!/usr/bin/env python3
"""Build the city list migration (personalised Home, founder 2026-10-31).

Source: GeoNames (https://www.geonames.org, CC BY 4.0) — cities5000.txt (every
town over 5,000 people) and admin1CodesASCII.txt (state names). Downloaded with
the founder's OK; not kept in the repo. Keeps every Indian town and the bigger
cities (50,000+) of the markets we plan to open next.

    python3 -I scripts/build-cities.py <cities5000.txt> <admin1CodesASCII.txt> > supabase/migrations/20261031110000_cities.sql
"""
import sys

MARKETS = ('AE', 'QA', 'GB', 'SG', 'MY', 'AU', 'US')
MARKET_MIN_POP = 50_000

# Well-known old and new names people still type. Either side may be the
# GeoNames name; the other becomes searchable ("Bangalore" finds Bengaluru).
RENAMES = [
    ('Bengaluru', 'Bangalore'), ('Mumbai', 'Bombay'), ('Kolkata', 'Calcutta'), ('Chennai', 'Madras'),
    ('Gurugram', 'Gurgaon'), ('Vadodara', 'Baroda'), ('Thiruvananthapuram', 'Trivandrum'),
    ('Visakhapatnam', 'Vizag', 'Vishakhapatnam'), ('Pune', 'Poona'), ('Kochi', 'Cochin'),
    ('Mysuru', 'Mysore'), ('Mangaluru', 'Mangalore'), ('Belagavi', 'Belgaum'), ('Hubballi', 'Hubli'),
    ('Kalaburagi', 'Gulbarga'), ('Vijayapura', 'Bijapur'), ('Shivamogga', 'Shimoga'), ('Tumakuru', 'Tumkur'),
    ('Kozhikode', 'Calicut'), ('Thrissur', 'Trichur'), ('Puducherry', 'Pondicherry'),
    ('Varanasi', 'Benares', 'Banaras'), ('Prayagraj', 'Allahabad'), ('Shimla', 'Simla'), ('Kanpur', 'Cawnpore'),
    ('Tiruchirappalli', 'Trichy', 'Tiruchi'), ('Bhubaneswar', 'Bhubaneshwar'), ('Guwahati', 'Gauhati'),
    ('Navi Mumbai', 'New Bombay'), ('Panaji', 'Panjim'), ('Sahibzada Ajit Singh Nagar', 'Mohali'),
    ('Ahmedabad', 'Amdavad'), ('Vijayawada', 'Bezawada'), ('Rajahmundry', 'Rajamahendravaram'),
    ('Thoothukudi', 'Tuticorin'), ('Udhagamandalam', 'Ooty'), ('Hyderabad', 'Hyd'),
]


def sql(s):
    return "'" + s.replace("'", "''") + "'"


def main(cities_path, admin1_path):
    regions = {}
    for line in open(admin1_path, encoding='utf8'):
        f = line.rstrip('\n').split('\t')
        if len(f) >= 3:
            regions[f[0]] = f[2]  # ASCII name
    aka_of = {}
    for group in RENAMES:
        for name in group:
            aka_of[name.lower()] = [n for n in group if n != name]

    rows = []
    for line in open(cities_path, encoding='utf8'):
        f = line.rstrip('\n').split('\t')
        cc, pop = f[8], int(f[14] or 0)
        if cc != 'IN' and not (cc in MARKETS and pop >= MARKET_MIN_POP):
            continue
        name = f[2].strip() or f[1].strip()  # ASCII name
        if not name:
            continue
        region = regions.get(f'{cc}.{f[10]}')
        aka = aka_of.get(name.lower()) if cc == 'IN' else None
        rows.append((int(f[0]), name, region, cc, round(float(f[4]), 3), round(float(f[5]), 3), pop,
                     '|'.join(aka) if aka else None))
    rows.sort(key=lambda r: (r[3] != 'IN', r[3], -r[6]))

    out = sys.stdout
    out.write("""-- ============================================================================
--  City list for personalised Home (founder 2026-10-31): the town people say
--  they're based in, and where a match is when its ground has no map pin.
--  Every Indian town over 5,000 people, plus cities over 50,000 in the markets
--  we open next (UAE, Qatar, UK, Singapore, Malaysia, Australia, US).
--  Data: GeoNames (https://www.geonames.org), CC BY 4.0 — credited on the
--  app's Legal page. Generated by scripts/build-cities.py; don't edit by hand.
--
--  Big file: run it from the terminal, not the SQL Editor:
--    npx supabase db query --linked --project-ref byjuxrajzvfjpnqvzwzv -f supabase/migrations/20261031110000_cities.sql
--  Safe to run again (rows are updated in place).
-- ============================================================================

create table if not exists cities (
  id integer primary key,          -- GeoNames id
  name text not null,
  region text,                     -- state / province
  country text not null check (country ~ '^[A-Z]{2}$'),
  lat real not null check (lat between -90 and 90),
  lng real not null check (lng between -180 and 180),
  population integer not null default 0,
  aka text                         -- other names people type, '|'-separated
);
create index if not exists cities_name_lower on cities (lower(name) text_pattern_ops);
alter table cities enable row level security;
drop policy if exists "read cities" on cities;
create policy "read cities" on cities for select using (true);
revoke insert, update, delete, truncate on cities from anon, authenticated;
grant select on cities to anon, authenticated;

insert into cities (id, name, region, country, lat, lng, population, aka) values
""")
    for i, r in enumerate(rows):
        sep = ',\n' if i < len(rows) - 1 else '\n'
        out.write('(%d,%s,%s,%s,%s,%s,%d,%s)%s' % (
            r[0], sql(r[1]), sql(r[2]) if r[2] else 'null', sql(r[3]), r[4], r[5], r[6],
            sql(r[7]) if r[7] else 'null', sep))
    out.write("""on conflict (id) do update set name = excluded.name, region = excluded.region, country = excluded.country,
  lat = excluded.lat, lng = excluded.lng, population = excluded.population, aka = excluded.aka;
""")
    sys.stderr.write(f'{len(rows)} cities\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
